export function resolveI18n(entry, lang, fEn, fYue){
  if(!entry) return null;
  const leveled = Array.isArray(entry[0]);
  const pick = (arr, lvl) => Array.isArray(arr) ? (arr[Math.min(arr.length-1, Math.max(0,(lvl||1)-1))]) : arr;
  const en = leveled ? pick(entry[0], fEn) : entry[0];
  const yue = leveled ? pick(entry[1], fYue) : entry[1];
  if(lang==='en') return en;
  if(lang==='yue') return yue;
  return en===yue ? en : en+' · '+yue;
}
